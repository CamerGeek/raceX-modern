from __future__ import annotations

import time

import pytest
from fastapi import FastAPI, HTTPException
from fastapi.testclient import TestClient

from app.api import races
from app.schemas.races import TurfomaniaQuinteAnalysisResponse

RACE = {"id": "race-1", "race_type": "flat"}


def _analysis(model_version: str = "initial") -> TurfomaniaQuinteAnalysisResponse:
    return TurfomaniaQuinteAnalysisResponse(
        race_id="race-1",
        race_type="flat",
        source="turfomania",
        row_count=1,
        columns=["N°", "CHEVAL"],
        rows=[{"N°": "4", "CHEVAL": "Horse Four"}],
        model_version=model_version,
        prognosis=[{"N°": "4", "CHEVAL": "Horse Four"}],
    )


def _run(
    run_id: str,
    created_at: str,
    *,
    version: str | None = None,
    analysis: TurfomaniaQuinteAnalysisResponse | None = None,
    race_id: str = "race-1",
) -> dict:
    payload = (analysis or _analysis()).model_dump(mode="json")
    return {
        "id": run_id,
        "race_id": race_id,
        "created_at": created_at,
        "model_version": payload["model_version"],
        "summary": {
            "homepage_cache_version": version or races.HOMEPAGE_QUINTE_CACHE_VERSION,
            "homepage_analysis": payload,
        },
        "prognosis": payload["prognosis"],
        "handicap": {},
        "raw_rows": payload["rows"],
    }


class FakeSupabase:
    def __init__(self, *, runs: list[dict], runner_updated_at: str = "2026-10-09T08:00:00+00:00"):
        self.runs = runs
        self.runner_updated_at = runner_updated_at
        self.inserted: list[dict] = []

    def select_one(self, table, *, filters=None, order_by=None):
        column, _, value = filters[0]
        if table == "races":
            return RACE
        if table == "analysis_runs":
            return next((run for run in self.runs if run["id"] == value), None)
        if table == "flat_race_runners":
            return {"updated_at": self.runner_updated_at}
        raise AssertionError(f"unexpected select table: {table}")

    def list(self, table, *, filters=None, limit=100, order_by=None):
        if table != "analysis_runs":
            raise AssertionError(f"unexpected list table: {table}")
        return list(self.runs)

    def insert(self, table, payload):
        assert table == "analysis_runs"
        self.inserted.append(payload)
        return payload


@pytest.fixture(autouse=True)
def clear_public_quinte_cache():
    races._public_quinte_cache.clear()
    yield
    races._public_quinte_cache.clear()


def test_list_analysis_runs_marks_the_newest_fresh_run_as_current(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    newest = _run("run-new", "2026-10-09T10:00:00+00:00", analysis=_analysis("newest"))
    older = _run("run-old", "2026-10-09T09:00:00+00:00", analysis=_analysis("older"))
    monkeypatch.setattr(races, "SupabaseClientWrapper", lambda: FakeSupabase(runs=[newest, older]))

    result = races.list_quinte_analysis_runs("race-1", _={})

    assert result["race_id"] == "race-1"
    assert [run["id"] for run in result["runs"]] == ["run-new", "run-old"]
    assert result["runs"][0]["is_current"] is True
    assert result["runs"][1]["is_current"] is False
    assert all(run["restorable"] for run in result["runs"])


def test_list_analysis_runs_explains_why_a_run_cannot_be_restored(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    stale = _run("run-stale", "2026-10-09T07:00:00+00:00")
    old_version = _run("run-v8", "2026-10-09T07:30:00+00:00", version="daily-quinte-composite-v8")
    monkeypatch.setattr(
        races,
        "SupabaseClientWrapper",
        lambda: FakeSupabase(runs=[stale, old_version]),
    )

    result = races.list_quinte_analysis_runs("race-1", _={})

    assert result["runs"][0]["restorable"] is False
    assert result["runs"][0]["restore_blocked_reason"] == "Runner data changed after this analysis"
    assert result["runs"][1]["restorable"] is False
    assert result["runs"][1]["restore_blocked_reason"] == "Generated by an older model cache version"
    assert not any(run["is_current"] for run in result["runs"])


def test_restore_appends_a_new_cache_row_and_clears_the_public_cache(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    previous = _run("run-old", "2026-10-09T09:00:00+00:00", analysis=_analysis("older"))
    fake = FakeSupabase(runs=[previous])
    monkeypatch.setattr(races, "SupabaseClientWrapper", lambda: fake)
    races._public_quinte_cache["2026-10-09"] = (time.monotonic(), {"rows": []})

    restored = races.restore_quinte_analysis_run("race-1", "run-old", _={})

    assert restored.model_version == "older"
    assert races._public_quinte_cache == {}
    assert len(fake.inserted) == 1
    inserted = fake.inserted[0]
    assert inserted["race_id"] == "race-1"
    assert inserted["summary"]["homepage_cache_version"] == races.HOMEPAGE_QUINTE_CACHE_VERSION
    assert inserted["summary"]["restored_from_run_id"] == "run-old"
    assert inserted["summary"]["homepage_analysis"] == previous["summary"]["homepage_analysis"]
    assert inserted["raw_rows"] == previous["raw_rows"]


