def test_analysis_history_requires_an_authenticated_admin() -> None:
    app = FastAPI()
    app.include_router(races.router, prefix="/api/v1")

    response = TestClient(app).get("/api/v1/races/race-1/analysis-runs")

    assert response.status_code == 401


def test_restore_routes_are_available_to_admins(monkeypatch: pytest.MonkeyPatch) -> None:
    previous = _run("run-old", "2026-10-09T09:00:00+00:00", analysis=_analysis("older"))
    fake = FakeSupabase(runs=[previous])
    monkeypatch.setattr(races, "SupabaseClientWrapper", lambda: fake)
    app = FastAPI()
    app.include_router(races.router, prefix="/api/v1")
    app.dependency_overrides[races.require_admin] = lambda: {"id": "admin-user", "role": "admin"}
    client = TestClient(app)

    listed = client.get("/api/v1/races/race-1/analysis-runs")
    restored = client.post("/api/v1/races/race-1/analysis-runs/run-old/restore")

    assert listed.status_code == 200
    assert [run["id"] for run in listed.json()["runs"]] == ["run-old"]
    assert restored.status_code == 200
    assert restored.json()["race_id"] == "race-1"
    assert restored.json()["model_version"] == "older"
